// Parses the `key: value` front matter of DUNGEON.md (no YAML lists: comma-separated values).
function parseDungeon(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return null;
  const f = {};
  m[1].split(/\r?\n/).forEach(l => { const i = l.indexOf(":"); if (i > 0) f[l.slice(0, i).trim()] = l.slice(i + 1).trim(); });
  const list = v => (v || "").split(",").map(x => x.trim().replace(/^\.\//, "")).filter(Boolean);
  return { name: f.name, icon: (f.icon || "").replace(/^\.\//, ""), status: f.status, tags: list(f.tags), preview: list(f.preview),
    ai: f.ai_images === "true", en: f.summary_en, pt: f.summary_pt };
}

const el = (tag, cls, text) => { const e = document.createElement(tag); if (cls) e.className = cls; if (text) e.textContent = text; return e; };
const IMG_EXT = /\.(png|svg|gif|webp|jpe?g)$/i;
// `icon` in DUNGEON.md: an image path in the repo (used as image) or an emoji.
function iconEl(p) {
  if (p.icon && IMG_EXT.test(p.icon)) {
    const i = el("img", "pix-img"); i.alt = ""; i.loading = "lazy";
    i.src = /^(https:\/\/raw\.githubusercontent\.com\/|\.\/)/.test(p.icon) ? p.icon : RAW(p.repo, p.icon);
    return i;
  }
  return el("span", "pix", p.icon || "◆");
}
function renderProjects() {
  const grid = document.getElementById("projects");
  grid.replaceChildren(...PROJECTS.map(p => {
    const a = el("a", "card"); a.href = `https://github.com/${ORG}/${p.repo}`; a.target = "_blank"; a.rel = "noopener";
    a.append(iconEl(p), el("h3", "", p.name), el("p", "", p[lang] || p.en || ""));
    if (p.preview.length) {
      const d = el("div", "previews");
      p.preview.slice(0, 4).forEach(src => { const i = el("img"); i.alt = ""; i.loading = "lazy";
        i.src = /^(https:\/\/raw\.githubusercontent\.com\/|\.\/)/.test(src) ? src : RAW(p.repo, src); d.append(i); });
      a.append(d);
      if (p.ai) a.append(el("small", "note", AI_NOTE[lang]));
    }
    const chips = el("div", "chips");
    if (p.status) chips.append(el("span", "chip status", p.status));
    p.tags.forEach(t => chips.append(el("span", "chip", t)));
    a.append(chips);
    return a;
  }));
}
const loadDungeon = p => fetch(RAW(p.repo, "DUNGEON.md")).then(r => r.ok ? r.text() : "").then(t => {
  const d = t && parseDungeon(t); if (!d) return;
  Object.keys(d).forEach(k => { if (d[k] && (!Array.isArray(d[k]) || d[k].length)) p[k] = d[k]; });
  renderProjects();
}).catch(() => {});
// Discovery: public org repos (no forks/archived, not this site). shortcut: unauthenticated API allows 60 req/h per visitor IP, on failure the PROJECTS fallback stays.
fetch(`https://api.github.com/orgs/${ORG}/repos?type=public&per_page=100`).then(r => r.ok ? r.json() : Promise.reject()).then(repos => {
  const live = repos.filter(r => !r.fork && !r.archived && r.name.toLowerCase() !== `${ORG}.github.io`.toLowerCase());
  const known = Object.fromEntries(PROJECTS.map(p => [p.repo, p]));
  PROJECTS.splice(0, PROJECTS.length, ...live.map(r => known[r.name] || { repo: r.name, name: r.name, tags: r.language ? [r.language] : [],
    preview: [], en: r.description || "", pt: r.description || "" }));
  renderProjects();
}).catch(() => {}).finally(() => PROJECTS.forEach(loadDungeon));

