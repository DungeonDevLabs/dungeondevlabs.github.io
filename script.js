let lang = "en";
try { lang = localStorage.getItem("lang") || ""; } catch (e) {}
if (!T[lang]) lang = (navigator.language || "en").toLowerCase().startsWith("pt") ? "pt" : "en";

function apply() {
  root.lang = lang === "pt" ? "pt-BR" : "en";
  document.querySelectorAll("[data-i18n]").forEach(e => e.textContent = T[lang][e.dataset.i18n]);
  document.querySelectorAll("[data-i18n-html]").forEach(e => e.innerHTML = T[lang][e.dataset.i18nHtml]);
  document.getElementById("lang").textContent = lang === "pt" ? "PT" : "EN";
}
document.getElementById("lang").onclick = () => {
  lang = lang === "pt" ? "en" : "pt";
  try { localStorage.setItem("lang", lang); } catch (e) {}
  apply();
};
document.getElementById("theme").onclick = () => {
  const t = root.dataset.theme === "dark" ? "light" : "dark";
  root.dataset.theme = t;
  try { localStorage.setItem("theme", t); } catch (e) {}
};
document.getElementById("y").textContent = new Date().getFullYear();
apply();
